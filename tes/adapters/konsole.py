"""Konsole: installs a colour scheme + a profile named "Terminal Experience Studio".

We deliberately do NOT change Konsole's default profile (Konsole rewrites its own settings
file on exit, so editing it while it runs is unreliable). The user picks the profile once:
Settings > Switch Profile > Terminal Experience Studio.
"""
from __future__ import annotations

from pathlib import Path

from ..core import paths
from ..core.content import clean_line
from ..core.fsutil import atomic_write
from ..core.themes import Theme, hex_to_rgb
from .base import ApplyResult, TerminalAdapter

SCHEME = "TerminalExperienceStudio"


def _rgb(h: str) -> str:
    return "%d,%d,%d" % hex_to_rgb(h)


class Konsole(TerminalAdapter):
    id = "konsole"
    name = "Konsole"
    binary = "konsole"
    features = frozenset({"colors", "palette", "font", "cursor_shape", "transparency"})

    @staticmethod
    def dir() -> Path:
        return paths.data_home() / "konsole"

    def config_exists(self) -> bool:
        return self.dir().is_dir()

    def render_scheme(self, t: Theme) -> str:
        L = ["# Generated by Terminal Experience Studio.",
             "[Background]", f"Color={_rgb(t.bg)}", "", "[BackgroundIntense]", f"Color={_rgb(t.bg)}", "",
             "[Foreground]", f"Color={_rgb(t.fg)}", "", "[ForegroundIntense]", f"Color={_rgb(t.fg)}", ""]
        for i in range(8):
            L += [f"[Color{i}]", f"Color={_rgb(t.palette[i])}", "", f"[Color{i}Intense]", f"Color={_rgb(t.palette[8 + i])}", ""]
        L += ["[General]", "Description=Terminal Experience Studio", f"Opacity={t.opacity / 100:.2f}", ""]
        return "\n".join(L)

    def render_profile(self, t: Theme) -> str:
        shape = {"block": 0, "beam": 1, "underline": 2}[t.cursor_shape]
        font = f"{clean_line(t.font, 80).replace(',', ' ')},{round(t.font_size)},-1,5,50,0,0,0,0,0"
        return "\n".join([
            "[Appearance]", f"ColorScheme={SCHEME}", f"Font={font}", "",
            "[Cursor Options]", f"CursorShape={shape}", "UseCustomCursorColor=true", f"CustomCursorColor={_rgb(t.cursor)}", "",
            "[General]", "Name=Terminal Experience Studio", "Parent=FALLBACK/", "",
        ])

    def apply(self, theme: Theme) -> ApplyResult:
        try:
            atomic_write(self.dir() / f"{SCHEME}.colorscheme", self.render_scheme(theme))
            atomic_write(self.dir() / "Terminal Experience Studio.profile", self.render_profile(theme))
        except OSError as exc:
            return ApplyResult(False, f"Couldn't write Konsole files: {exc}")
        res = ApplyResult(True, "Konsole profile created.", applied=sorted(self.features))
        res.notes.append("In Konsole choose: Settings > Switch Profile > Terminal Experience Studio.")
        self._skip_unsupported(theme, res)
        return res

    def reset(self) -> ApplyResult:
        for name in (f"{SCHEME}.colorscheme", "Terminal Experience Studio.profile"):
            try:
                (self.dir() / name).unlink()
            except FileNotFoundError:
                pass
        return ApplyResult(True, "Removed the Terminal Experience Studio profile from Konsole.")
