"""Alacritty (TOML): writes tes-theme.toml and imports it from alacritty.toml in a managed block.

Alacritty >= 0.14 wants `[general] import = [...]`; 0.13 wants a top-level `import = [...]`.
We never create a duplicate [general] table and never overwrite an existing `import` key.
"""
from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path

from ..core import backups, paths
from ..core.content import clean_line
from ..core.fsutil import atomic_write, read_text
from ..core.shellblock import get_block, set_block
from ..core.themes import PALETTE_NAMES, Theme
from .base import END, START, ApplyResult, TerminalAdapter, managed_include, remove_managed

_GENERAL = re.compile(r"^\s*\[general\]\s*(#.*)?$", re.M)
_IMPORT = re.compile(r"^\s*(general\.)?import\s*=", re.M)


def _version() -> tuple[int, int] | None:
    try:
        out = subprocess.run(["alacritty", "--version"], capture_output=True, text=True, timeout=3).stdout
        m = re.search(r"(\d+)\.(\d+)", out)
        return (int(m[1]), int(m[2])) if m else None
    except (OSError, subprocess.SubprocessError):
        return None


class Alacritty(TerminalAdapter):
    id = "alacritty"
    name = "Alacritty"
    binary = "alacritty"
    features = frozenset({"colors", "palette", "font", "cursor_shape", "transparency"})

    @staticmethod
    def conf() -> Path:
        return paths.config_home() / "alacritty" / "alacritty.toml"

    @staticmethod
    def theme_file() -> Path:
        return paths.config_home() / "alacritty" / "tes-theme.toml"

    def config_exists(self) -> bool:
        return self.conf().exists()

    def render(self, t: Theme) -> str:
        q = lambda s: json.dumps(s)
        L = ["# Generated by Terminal Experience Studio - changes here are overwritten.",
             "[colors.primary]", f"background = {q(t.bg)}", f"foreground = {q(t.fg)}", "",
             "[colors.cursor]", f"text = {q(t.bg)}", f"cursor = {q(t.cursor)}", ""]
        L += ["[colors.normal]"] + [f"{n} = {q(c)}" for n, c in zip(PALETTE_NAMES, t.palette[:8])] + [""]
        L += ["[colors.bright]"] + [f"{n} = {q(c)}" for n, c in zip(PALETTE_NAMES, t.palette[8:])] + [""]
        L += ["[font]", f"size = {t.font_size:g}", "", "[font.normal]", f"family = {q(clean_line(t.font, 80))}", "",
              "[window]", f"opacity = {t.opacity / 100:.2f}", "",
              "[cursor.style]", f"shape = {q(t.cursor_shape.capitalize())}", ""]
        return "\n".join(L)

    # ----------------------------------------------------------- import wiring
    def _wire(self, version) -> tuple[Path | None, str | None]:
        """Returns (backup, problem). `problem` is a manual-step message when we can't safely edit."""
        conf = self.conf()
        line = f"import = [{json.dumps(str(self.theme_file()))}]"
        general_mode = version is None or version >= (0, 14)
        text = read_text(conf)
        if get_block(text, START, END) is not None:
            return managed_include(conf, "\n".join(self._block_body(line, general_mode, text)), "alacritty"), None
        if not general_mode:
            return managed_include(conf, line, "alacritty", top_level=True), None
        if _GENERAL.search(text):
            if _IMPORT.search(text):
                return None, (f"Your alacritty.toml already has an import list. Add this path to it yourself:\n"
                              f"{self.theme_file()}")
            bk = backups.backup_file(conf, "alacritty")
            m = _GENERAL.search(text)
            block = f"{START}\n{line}\n{END}"
            atomic_write(conf, text[: m.end()] + "\n" + block + text[m.end():])
            return bk, None
        return managed_include(conf, f"[general]\n{line}", "alacritty"), None

    @staticmethod
    def _block_body(line: str, general_mode: bool, text: str) -> list[str]:
        # keep the existing block's shape ([general] header only if it was already there)
        body = get_block(text, START, END) or ""
        return (["[general]"] if "[general]" in body else []) + [line]

    def apply(self, theme: Theme) -> ApplyResult:
        res = ApplyResult(True, "")
        ver = _version()
        if ver is not None and ver < (0, 13):
            return ApplyResult(False, "This Alacritty uses the old YAML config. Please update to 0.13 or newer (TOML).")
        try:
            atomic_write(self.theme_file(), self.render(theme))
            res.backup, problem = self._wire(ver)
        except OSError as exc:
            return ApplyResult(False, f"Couldn't write Alacritty's configuration: {exc}")
        if problem:
            res.notes.append(problem)
        res.applied = [f for f in self.features]
        self._skip_unsupported(theme, res)
        res.notes.append("Alacritty reloads its config automatically.")
        res.message = "Alacritty theme written." if not problem else "Theme file written - one manual step needed."
        return res

    def reset(self) -> ApplyResult:
        bk = remove_managed(self.conf(), "alacritty")
        try:
            self.theme_file().unlink()
        except FileNotFoundError:
            pass
        return ApplyResult(True, "Alacritty is back to its own settings.", backup=bk)
