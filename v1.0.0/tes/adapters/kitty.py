"""Kitty: writes tes-theme.conf and includes it from kitty.conf inside a managed block."""
from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

from ..core import paths
from ..core.content import clean_line
from ..core.fsutil import atomic_write
from ..core.themes import Theme
from .base import ApplyResult, TerminalAdapter, managed_include, remove_managed


class Kitty(TerminalAdapter):
    id = "kitty"
    name = "Kitty"
    binary = "kitty"
    features = frozenset({"colors", "palette", "font", "cursor_shape", "transparency", "bg_image"})

    @staticmethod
    def conf() -> Path:
        return paths.config_home() / "kitty" / "kitty.conf"

    @staticmethod
    def theme_file() -> Path:
        return paths.config_home() / "kitty" / "tes-theme.conf"

    def config_exists(self) -> bool:
        return self.conf().exists()

    def render(self, t: Theme, res: ApplyResult | None = None) -> str:
        L = ["# Generated by Terminal Experience Studio - changes here are overwritten.",
             f"foreground {t.fg}", f"background {t.bg}", f"cursor {t.cursor}", f"cursor_text_color {t.bg}",
             f"selection_foreground {t.bg}", f"selection_background {t.fg}"]
        L += [f"color{i} {c}" for i, c in enumerate(t.palette)]
        L += [f"font_family {clean_line(t.font, 80)}", f"font_size {t.font_size:g}",
              f"cursor_shape {t.cursor_shape}", f"background_opacity {t.opacity / 100:.2f}"]
        if t.bg_image:
            img = Path(t.bg_image).expanduser()
            if img.suffix.lower() == ".png" and img.is_file():
                L += [f"background_image {img}", "background_image_layout cscaled"]
            elif res is not None:
                res.skipped["bg_image"] = "Kitty only supports PNG background images, and the file must exist."
        return "\n".join(L) + "\n"

    def apply(self, theme: Theme) -> ApplyResult:
        res = ApplyResult(True, "")
        try:
            atomic_write(self.theme_file(), self.render(theme, res))
            res.backup = managed_include(self.conf(), f"include {self.theme_file().name}", "kitty")
        except OSError as exc:
            return ApplyResult(False, f"Couldn't write Kitty's configuration: {exc}")
        res.applied = [f for f in self.features if f not in res.skipped and (f != "bg_image" or theme.bg_image)]
        self._skip_unsupported(theme, res)
        if shutil.which("pkill"):  # Kitty reloads its config on SIGUSR1
            subprocess.run(["pkill", "-USR1", "-x", "kitty"], check=False)
            res.notes.append("Open Kitty windows were reloaded live.")
        res.message = "Kitty theme applied."
        return res

    def reset(self) -> ApplyResult:
        bk = remove_managed(self.conf(), "kitty")
        try:
            self.theme_file().unlink()
        except FileNotFoundError:
            pass
        if shutil.which("pkill"):
            subprocess.run(["pkill", "-USR1", "-x", "kitty"], check=False)
        return ApplyResult(True, "Kitty is back to its own settings.", backup=bk)
